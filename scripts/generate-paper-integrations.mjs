/** Complete paper editions: all derived inventories and Markdown come from MDX. */
import fs from 'node:fs/promises';
import path from 'node:path';
import yaml from 'js-yaml';
export async function generatePaperIntegrations(root=process.cwd()) {
 const papers=JSON.parse(await fs.readFile(path.join(root,'src/config/paper-integrations.json'),'utf8'));
 const chapters=[]; const imports=[]; const manifests=[];
 for(const paper of papers){
  const dir=path.join(root,'content/paper-integrations',paper.id);
  const files=(await fs.readdir(dir)).filter(name=>name.endsWith('.mdx')).sort();
  if(!files.length)throw new Error(`No chapters for ${paper.id}`);
  let markdown=`# ${paper.title}\n\n${paper.subtitle}\n\nJeremy Rodgers · ${paper.date}\n\nDOI: https://doi.org/${paper.doi}\n\n`;
  const records=[];
  for(const file of files){
   const sourcePath=`content/paper-integrations/${paper.id}/${file}`;
   const text=await fs.readFile(path.join(dir,file),'utf8');
   const match=text.match(/^---\r?\n([\s\S]*?)\r?\n---\s*\n/);
   if(!match)throw new Error(`Missing frontmatter ${sourcePath}`);
   const meta=yaml.load(match[1]); const body=text.slice(match[0].length); const slug=file.slice(0,-4);
   if(!meta.title||!meta.description||!Number.isFinite(meta.order))throw new Error(`Incomplete chapter metadata ${sourcePath}`);
   const anchors=[...body.matchAll(/<a\s+id=["']([^"']+)["'][^>]*>/g)].map(m=>m[1]);
   if(new Set(anchors).size!==anchors.length)throw new Error(`Duplicate anchors ${sourcePath}`);
   const sections=[...body.matchAll(/<a\s+id=["']([^"']+)["'][^>]*><\/a>\s*\n+#{2,4}\s+([^\n]+)/g)].map(m=>({id:m[1],title:m[2].replace(/[*`]/g,'')}));
   const record={paperId:paper.id,slug,title:String(meta.title),description:String(meta.description),order:meta.order,url:`${paper.url}/${slug}`,sourcePath,sections,anchors,words:body.split(/\s+/).length};
   records.push(record);chapters.push(record);
   imports.push(` ${JSON.stringify(paper.id+'/'+slug)}: () => import(${JSON.stringify('../../'+sourcePath)})`);
   markdown+=`\n\n## ${meta.title}\n\n${body}\n`;
  }
  records.sort((a,b)=>a.order-b.order);
  const destination=path.join(root,'public',paper.markdownUrl);await fs.mkdir(path.dirname(destination),{recursive:true});await fs.writeFile(destination,markdown);
  manifests.push({schemaVersion:1,publication:paper,kind:'complete-translated-web-edition',updated:'2026-10-23',chapters:records,completeMarkdown:paper.markdownUrl,originalPdf:paper.pdfUrl});
 }
 chapters.sort((a,b)=>a.paperId.localeCompare(b.paperId)||a.order-b.order);
 await fs.writeFile(path.join(root,'src/generated/paper-integrations.ts'),`// AUTO-GENERATED by scripts/generate-paper-integrations.mjs; do not edit.\nexport const integrationChapters = ${JSON.stringify(chapters,null,2)};\nexport const integrationImports = {\n${imports.join(',\n')}\n};\n`);
 await fs.writeFile(path.join(root,'public/publications/consciousness/new-papers/inventory.json'),JSON.stringify(manifests,null,2)+'\n');
}
